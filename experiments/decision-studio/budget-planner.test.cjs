'use strict';
const assert=require('node:assert/strict');
const {compare}=require('./dist/budget-planner.js');
const example={mode:'paid',outcome:'purchase',commercial:true,capacity:100,contributionMinor:50000,ceilingMinor:null,cashMinor:null,days:7,evidence:'synthetic',productionMinor:0,serviceMinor:0};
const run=patch=>compare({...example,...patch});
assert.equal(run({evidence:'none'}).status,'missing');
assert.equal(run({capacity:null}).candidates.length,0);
assert.equal(run({contributionMinor:null}).candidates.length,0);
assert.equal(run({ceilingMinor:0}).status,'no_paid');
assert.equal(run({mode:'organic'}).status,'no_paid');
assert.equal(run({capacity:0}).status,'no_feasible');
assert.equal(run({capacity:9}).status,'no_feasible');
assert.equal(run({ceilingMinor:99999}).status,'no_feasible');
assert.equal(run({contributionMinor:100}).status,'no_feasible');
const normal=run({});
assert.equal(normal.status,'conditional');
assert.equal(normal.candidates.length,2);
assert.ok(normal.candidates.every(c=>c.resultsHigh<=100));
assert.ok(normal.candidates.every(c=>c.contributionLowMinor>0));
assert.ok(normal.candidates.every(c=>c.evidenceLabel.includes('Sentetik')));
assert.equal(normal.executionAuthorized,false);
assert.equal(normal.publicationEnabled,false);
assert.ok(Object.isFrozen(normal.candidates[0].assumptions));
assert.equal(run({ceilingMinor:100000}).candidates.length,1);
assert.equal(run({ceilingMinor:100000}).candidates[0].mediaMinor,100000);
assert.equal(run({cashMinor:99999}).status,'no_feasible');
assert.equal(run({cashMinor:100000}).candidates.length,1);
assert.equal(run({productionMinor:1234,serviceMinor:1000,ceilingMinor:100000}).candidates[0].campaignCostMinor,102234);
assert.equal(run({productionMinor:null}).candidates[0].campaignCostMinor,null);
assert.equal(run({productionMinor:null}).candidates[0].contributionLowMinor,null);
assert.equal(run({productionMinor:null,cashMinor:200000}).status,'no_feasible');
assert.equal(run({outcome:'traffic',commercial:false,contributionMinor:null}).candidates[0].contributionLowMinor,null);
assert.equal(run({outcome:'traffic',commercial:false,contributionMinor:null}).candidates[0].resultUnit,'varsayımsal hedef eylem');
for(const outcome of ['traffic','message','visit','lead_form'])assert.throws(()=>run({outcome,commercial:true}));
for(const [key,values] of Object.entries({ceilingMinor:[undefined,NaN,-1,1.5,'100',true],capacity:[undefined,NaN,-1,.5,'10'],days:[0,366,NaN,1.5],productionMinor:[undefined,-1,1.2],evidence:['live',undefined]}))for(const value of values)assert.throws(()=>run({[key]:value}));
assert.deepEqual(compare(example),normal);
assert.equal(example.ceilingMinor,null);
console.log('Budget planner: missing/zero/ceiling, finite candidates, capacity/cash/economics, unknown costs, immutability and strict inputs passed.');
